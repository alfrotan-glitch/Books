"""Phase 4–5 language pass (readability): runs on manuscript/master.md after edit_master.py.

- Global rules: fixed, meaning-neutral Afghan-Dari style normalisations.
- REWRITE: long or tangled sentences split or reordered; the meaning is kept exactly.
- XREF: vague cross-references ("در فصل معاینه سیستم عصبی") -> chapter numbers.
- MED: two sourced scientific corrections (logged in CHANGELOG-editorial.md).
- Pedagogy: chapter objectives / key points / self-test (tools/pedagogy/*.md).

Every literal is required to match; the script aborts otherwise, so nothing is
silently skipped. Counts go to build/style-report.txt.
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DST = ROOT / "manuscript/master.md"
REPORT = []
t = DST.read_text(encoding="utf-8")


def rx(pat, rep, label):
    global t
    t, n = re.subn(pat, rep, t)
    REPORT.append(f"{n:5d}  {label}")


def lit(old, new, label, count=1):
    global t
    n = t.count(old)
    if n != count:
        sys.exit(f"ABORT style '{label}': found {n}x, expected {count}\n  {old[:90]}")
    t = t.replace(old, new)
    REPORT.append(f"{n:5d}  {label}")


